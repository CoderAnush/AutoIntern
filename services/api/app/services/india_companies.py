def get_active_adapters() -> list[dict]:
    """Return registry entries that have live ingestion enabled."""
    # Deduplicate by (ats_provider, board_token) to avoid duplicate API calls
    seen = set()
    adapters = []
    for co in INDIA_COMPANY_REGISTRY:
        if not co["live_ingestion"] or not co["board_token"]:
            continue
        key = (co["ats_provider"], co["board_token"])
        if key in seen:
            continue
        seen.add(key)
        adapters.append({
            "name": co["canonical_name"],
            "adapter": co["ats_provider"],
            "board_token": co["board_token"],
            "is_indian_origin": co["is_indian_origin"],
            "careers_url": co["careers_url"],
        })
    return adapters


def get_indian_origin_names() -> set[str]:
    """Return canonical names + aliases of Indian-origin companies for ranking."""
    names: set[str] = set()
    for co in INDIA_COMPANY_REGISTRY:
        if co["is_indian_origin"]:
            names.add(co["canonical_name"].lower())
            for alias in co.get("aliases", []):
                names.add(alias.lower())
    return names


def total_count() -> int:
    return len(INDIA_COMPANY_REGISTRY)


def count_with_ingestion() -> int:
    return sum(1 for c in INDIA_COMPANY_REGISTRY if c["live_ingestion"])
